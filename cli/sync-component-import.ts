import fs from 'fs'
import * as glob from 'glob'
import path from 'path'

const base = path.join(__dirname, '..', 'components')
const components = glob.sync(path.join(base, '**', 'package.json').split(path.sep).join(path.posix.sep))
  .filter(p => !p.includes('node_modules'))
  .map(p => path.dirname(p))
components.sort()

function componentSlug(component: string) {
  return path.relative(base, component).replace(/[/-]/g, '_')
}

fs.writeFileSync(path.join(base, 'index.ts'), [
  `/**`,
  ` * This file is autogenerated by cli/sync-component-import.ts`,
  ` *  and exports all metanodes recursively in this directory.`,
  ' * Use `npm run codegen:components`.',
  ` */`,
  ``,
  `import { MetaNode, MetaNodesFromExports } from "@/spec/metanode"`,
  `export const components: string[] = []`,
  `export const metanodes: MetaNode[] = []`,
  ...components
    .flatMap(component => {
      const componentPath = path.relative(base, component)
      const slug = componentSlug(component)
      return [
        `import * as ${slug} from ${JSON.stringify(`./${componentPath}`)}`,
        `import ${slug}_packageJson from ${JSON.stringify(`./${componentPath}/package.json`)}`,
        `metanodes.push(...MetaNodesFromExports(${slug}, ${slug}_packageJson))`,
        `components.push(${JSON.stringify(componentPath)})`,
      ]
    }),
  ].join('\n')
)

const componentRouters = components
  .filter(component => fs.existsSync(path.join(component, 'trpc.ts')))
  .map(component => {
    const manifest = JSON.parse(fs.readFileSync(path.join(component, 'package.json'), 'utf8')) as { name: string }
    const name = manifest.name.includes('/') ? manifest.name.slice(manifest.name.lastIndexOf('/') + 1) : manifest.name
    if (!/^[A-Za-z_$][\w$]*$/.test(name)) throw new Error(`Component router name is not a valid identifier: ${manifest.name}`)
    return { component, name, slug: `${componentSlug(component)}Router` }
  })

const duplicateRouterNames = componentRouters
  .map(({ name }) => name)
  .filter((name, index, names) => names.indexOf(name) !== index)
if (duplicateRouterNames.length > 0) throw new Error(`Duplicate component router names: ${[...new Set(duplicateRouterNames)].join(', ')}`)

fs.writeFileSync(path.join(base, 'trpc.ts'), [
  `/**`,
  ` * This file is autogenerated by cli/sync-component-import.ts`,
  ` *  and composes the tRPC routers exported by component-local trpc.ts files.`,
  ' * Use `npm run codegen:components`.',
  ` */`,
  ``,
  `import { router } from '@/app/trpc/init'`,
  ...componentRouters.map(({ component, slug }) =>
    `import ${slug} from ${JSON.stringify(`./${path.relative(base, component)}/trpc`)}`
  ),
  ``,
  `export const componentRouters = router({`,
  ...componentRouters.map(({ name, slug }) => `  ${name}: ${slug},`),
  `})`,
  ``,
].join('\n'))
